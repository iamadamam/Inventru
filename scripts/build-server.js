'use strict';
// Builds dist-server\InventruServer.exe: one file (Node.js single executable application) with the server, the TV
// dashboard and the setup page inside, then gives it the Inventru name, version and icon (shown in Task Manager,
// file Properties and Explorer). Usage: npm run build:server
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const pkg = require('../package.json');
const { VERSION } = require('../server/server');

if (VERSION !== pkg.version) throw new Error(`server/server.js VERSION ${VERSION} differs from package.json ${pkg.version}`);
const root = path.join(__dirname, '..');
const out = path.join(root, 'dist-server');
fs.mkdirSync(out, { recursive: true });
for (const f of fs.readdirSync(out)) fs.rmSync(path.join(out, f), { recursive: true, force: true }); // empty it (the folder may be open in a window)

// 1) bundle the server's modules into one CommonJS file (a single executable can only require Node built-ins)
const modules = ['server/cli.js', 'server/server.js', 'src/core/stockbook.js', 'src/core/batch.js', 'src/core/jsonfile.js', 'src/core/csv.js'];
let bundle = `'use strict';
// Generated by scripts/build-server.js - do not edit.
const __defs = {}; const __cache = {};
function __load(id) {
  if (__cache[id]) return __cache[id].exports;
  const def = __defs[id]; if (!def) throw new Error('bundle: missing module ' + id);
  const module = { exports: {} }; __cache[id] = module;
  const dir = id.split('/').slice(0, -1).join('/');
  const req = (spec) => {
    if (!spec.startsWith('.')) return require(spec);
    const stack = [];
    for (const p of (dir + '/' + spec).split('/')) { if (p === '..') stack.pop(); else if (p && p !== '.') stack.push(p); }
    let target = stack.join('/'); if (!target.endsWith('.js')) target += '.js';
    return __load(target);
  };
  def(module, module.exports, req, dir);
  return module.exports;
}
`;
for (const m of modules) {
  bundle += `__defs[${JSON.stringify(m)}] = function (module, exports, require, __dirname) {\n${fs.readFileSync(path.join(root, m), 'utf8')}\n};\n`;
}
bundle += `__load('server/cli.js');\n`;
const bundleFile = path.join(out, 'server-bundle.js');
fs.writeFileSync(bundleFile, bundle);

// 2) single executable, web pages embedded
const web = (f) => path.join(root, 'server', 'web', f);
const exe = path.join(out, 'InventruServer.exe');
const seaConfig = {
  main: bundleFile,
  output: exe,
  disableExperimentalSEAWarning: true,
  useSnapshot: false,
  useCodeCache: false,
  execArgvExtension: 'none', // NODE_OPTIONS and --node-options can't change how the server runs
  assets: {
    'index.html': web('index.html'), 'dashboard.js': web('dashboard.js'), 'dashboard.css': web('dashboard.css'),
    'setup.html': web('setup.html'), 'setup.js': web('setup.js'), 'setup.css': web('setup.css'), 'favicon.svg': web('favicon.svg'),
    'icons.js': path.join(root, 'src', 'renderer', 'icons.js'),
  },
};
const cfgFile = path.join(out, 'sea-config.json');
fs.writeFileSync(cfgFile, JSON.stringify(seaConfig, null, 2));
execFileSync(process.execPath, ['--build-sea', cfgFile], { stdio: 'inherit' });

// 3) name, version and icon (rcedit, the same tool electron-builder uses for Inventru.exe)
const rcedit = path.join(process.env.LOCALAPPDATA || '', 'electron-builder', 'Cache', 'winCodeSign', 'winCodeSign-2.6.0', 'rcedit-x64.exe');
if (!fs.existsSync(rcedit)) throw new Error(`rcedit not found at ${rcedit} - run "npm run dist" once (electron-builder downloads it)`);
execFileSync(rcedit, [exe,
  '--set-version-string', 'FileDescription', 'Inventru server',
  '--set-version-string', 'ProductName', 'Inventru',
  '--set-version-string', 'CompanyName', 'Inventru',
  '--set-version-string', 'LegalCopyright', pkg.copyright,
  '--set-version-string', 'InternalName', 'InventruServer',
  '--set-version-string', 'OriginalFilename', 'InventruServer.exe',
  '--set-file-version', pkg.version, '--set-product-version', pkg.version,
  '--set-icon', path.join(root, 'build', 'icon.ico'),
], { stdio: 'inherit' });

// 4) it must still start (the embedded server code is intact)
const v = execFileSync(exe, ['--version'], { encoding: 'utf8', env: { ...process.env, NODE_OPTIONS: '' } }).trim();
if (v !== pkg.version) throw new Error(`built server says "${v}", expected ${pkg.version}`);
fs.rmSync(bundleFile); fs.rmSync(cfgFile);
console.log(`built ${exe} (${(fs.statSync(exe).size / 1048576).toFixed(1)} MB), version ${v}`);
